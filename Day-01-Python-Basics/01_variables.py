
# Day 01 - Python Variables and Data Types

# Variables
name = "James"
age = 22
role = "Python Developer"
salary = 45000.50
is_learning = True

# Display values
print("Name:", name)
print("Age:", age)
print("Role:", role)
print("Salary:", salary)
print("Learning:", is_learning)

# Display data types
print("\nData Types:")
print(type(name))
print(type(age))
print(type(role))
print(type(salary))
print(type(is_learning))
