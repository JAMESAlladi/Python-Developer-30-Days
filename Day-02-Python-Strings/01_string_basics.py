# Day 02 - Python String Basics

# 1. String creation
name = "James"
language = "Python"

# 2. String indexing
print(name[0])
print(name[-1])

# 3. String slicing
print(name[0:3])
print(name[::-1])

# 4. String length
print(len(name))

# 5. String concatenation
print(name + " loves " + language)

# 6. String repetition
print(language * 3)

# 7. Check substring
print("Jam" in name)
