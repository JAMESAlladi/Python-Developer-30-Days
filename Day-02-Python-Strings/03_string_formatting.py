# Day 02 - String Formatting

name = "James"
age = 22
skill = "Machine Learning"

# f-string
print(f"My name is {name}")

# Multiple variables
print(f"I am {age} years old.")

# Expressions
print(f"Next year I will be {age + 1}")

# Formatting decimals
score = 95.6789
print(f"Accuracy: {score:.2f}%")
